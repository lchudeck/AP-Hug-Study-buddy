const {readFileSync}=require('fs');
const vm=require('vm');
const assert=require('assert/strict');
const listeners={};
let calls=0;
const names=['flashFlip','setFlashStatus','updateScaffold','setExamAnswer','setExamFrq','selectExam','resetExam','go','simStart','pmStart'];
const context={window:{},location:{origin:'https://www.apstudybuddy.com',pathname:'/'},document:{title:'Study Buddy',head:{appendChild(){}},createElement(){return {}},addEventListener(type,fn){(listeners[type]??=[]).push(fn)}}};
for(const name of names)context.window[name]=function(){calls++;return 'preserved'};
vm.createContext(context);
vm.runInContext(readFileSync('analytics.js','utf8'),context);
const w=context.window;
const events=()=>w.dataLayer.filter(x=>x[0]==='event');
assert.equal(w.flashFlip(),'preserved');w.flashFlip();w.setFlashStatus('got');
assert.equal(events().filter(x=>x[1]==='flashcards_started').length,1);
w.updateScaffold('A','PRIVATE RESPONSE');w.updateScaffold('B','PRIVATE RESPONSE');
assert.equal(events().filter(x=>x[1]==='frq_practice_started').length,1);
w.setExamAnswer(0,2);w.setExamFrq(0,'PRIVATE RESPONSE');
assert.equal(events().filter(x=>x[1]==='practice_test_started').length,1);
w.resetExam();w.setExamAnswer(0,1);
assert.equal(events().filter(x=>x[1]==='practice_test_started').length,2);
w.go('home');w.flashFlip();
assert.equal(events().filter(x=>x[1]==='flashcards_started').length,2);
w.simStart('mcq');w.pmStart();
assert(events().some(x=>x[1]==='final_ap_started'));
assert(events().some(x=>x[1]==='practice_started'));
assert(!JSON.stringify(w.dataLayer).includes('PRIVATE RESPONSE'));
assert(calls>0);
console.log('Activity starts deduplicated, original behavior preserved, answer text excluded.');
